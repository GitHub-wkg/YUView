#include <QTemporaryFile>
#include <array>
#include <gtest/gtest.h>
#include <parser/AVC/ParserAnnexBAVC.h>
#include <parser/common/NalUnitIndex.h>

TEST(NalUnitParser, RealAvcBFramesMapEverySliceToDisplayOrder)
{
  // Four x264 pictures, two slices each, including reordered B pictures; SEI omitted.
  const unsigned char bytes[] = {
    0x00, 0x00, 0x00, 0x01, 0x67, 0x64, 0x00, 0x0a, 0xac, 0xd9, 0x49, 0x6c, 0x04, 0x40, 0x00,
    0x00, 0x03, 0x00, 0x40, 0x00, 0x00, 0x03, 0x02, 0x03, 0xc4, 0x89, 0x65, 0x80, 0x00, 0x00,
    0x00, 0x01, 0x68, 0xeb, 0xe3, 0xcb, 0x22, 0xc0, 0x00, 0x00, 0x01, 0x65, 0x88, 0x84, 0x00,
    0x12, 0xff, 0xfe, 0xe8, 0xc9, 0xfc, 0xcb, 0x2b, 0x2f, 0xe3, 0xd4, 0x37, 0xb3, 0x46, 0x29,
    0xb3, 0x49, 0xa7, 0x1f, 0x00, 0x00, 0x01, 0x65, 0x62, 0x21, 0x00, 0x04, 0xbf, 0xfe, 0xe8,
    0xc9, 0xfc, 0xcb, 0x2b, 0x2f, 0xe3, 0xd4, 0x37, 0xb3, 0x46, 0x29, 0xb3, 0x49, 0xa7, 0x1f,
    0x00, 0x00, 0x00, 0x01, 0x41, 0x9a, 0x23, 0x6c, 0x41, 0x0f, 0xfe, 0xb8, 0x00, 0x00, 0x01,
    0x41, 0x66, 0x88, 0xdb, 0x10, 0x43, 0xff, 0xfe, 0xb8, 0x00, 0x00, 0x00, 0x01, 0x41, 0x9e,
    0x41, 0x78, 0x82, 0x3f, 0x69, 0x41, 0x00, 0x00, 0x01, 0x41, 0x67, 0x90, 0x5e, 0x20, 0x8f,
    0xff, 0x69, 0x41, 0x00, 0x00, 0x00, 0x01, 0x01, 0x9e, 0x62, 0x6a, 0x41, 0x0f, 0x70, 0xc0,
    0x00, 0x00, 0x01, 0x01, 0x67, 0x98, 0x9a, 0x90, 0x43, 0xff, 0x70, 0xc0,
  };
  QTemporaryFile file;
  ASSERT_TRUE(file.open());
  ASSERT_EQ(file.write(reinterpret_cast<const char *>(bytes), sizeof(bytes)),
            qint64(sizeof(bytes)));
  file.close();
  parser::ParserAnnexBAVC parser;
  parser.enableModel();
  ASSERT_TRUE(
    parser.runParsingOfFile(std::filesystem::u8path(file.fileName().toUtf8().constData())));
  NalUnitIndex units;
  units.build(parser.getParsedTree(), parser.getFrameByteRanges(), -1);
  ASSERT_EQ(parser.getFrameByteRanges().size(), 4u);
  ASSERT_EQ(units.units().size(), 10u);
  std::array<int, 4> slices{};
  int                previousFrame = -1;
  bool               reordered     = false;
  for (const auto &unit : units.units())
    if (unit.frame)
    {
      ASSERT_GE(*unit.frame, 0);
      ASSERT_LT(*unit.frame, 4);
      ++slices[size_t(*unit.frame)];
      reordered     = reordered || previousFrame > *unit.frame;
      previousFrame = *unit.frame;
    }
  for (const auto count : slices)
    EXPECT_EQ(count, 2);
  EXPECT_TRUE(reordered);
}